export const ODD_WORD_POINTS = 10;

export interface OddWordRound {
  words: string[];
  oddIdx: number;
  odd: string;
  link: string;
  picked?: number;
  done: boolean;
  won: boolean;
}

function shuffle<T>(items: T[]): T[] {
  const out = items.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

export function createOddWordRound(previousOdd?: string): OddWordRound {
  const pool = ODD_WORD_PUZZLES.filter(p => p.odd !== previousOdd);
  const chosen = (pool.length ? pool : ODD_WORD_PUZZLES)[
    Math.floor(Math.random() * (pool.length ? pool.length : ODD_WORD_PUZZLES.length))
  ];
  const words = shuffle([...chosen.four, chosen.odd]);
  return {
    words,
    oddIdx: words.indexOf(chosen.odd),
    odd: chosen.odd,
    link: chosen.link,
    done: false,
    won: false
  };
}

export function pickOddWord(round: OddWordRound, idx: number): OddWordRound {
  if (round.done || idx < 0 || idx >= round.words.length) return round;
  const won = idx === round.oddIdx;
  return { ...round, picked: idx, done: true, won };
}
