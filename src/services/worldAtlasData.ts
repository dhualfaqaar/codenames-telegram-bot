function deterministicDistractors(list: FlagSpec[], currentIdx: number, field: 'name' | 'capital'): [string, string, string] {
  const target = list[currentIdx];
  const sameRegion = list.filter((x, i) => i !== currentIdx && x.region === target.region && Boolean(x[field]) && x[field] !== target[field]);
  const pool = sameRegion.length >= 6 ? sameRegion : list.filter((x, i) => i !== currentIdx && Boolean(x[field]) && x[field] !== target[field]);
  const out: string[] = [];
  let step = (currentIdx * 7 + 3) % pool.length;
  while (out.length < 3) {
    const cand = String(pool[step % pool.length][field]);
    if (!out.includes(cand) && cand !== target[field]) out.push(cand);
    step += 5;
  }
  return [out[0], out[1], out[2]];
}

