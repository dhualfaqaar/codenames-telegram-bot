export const WORLD_FLAGS_FULL: GQRow[] = ATLAS_ENTRIES.map((entry, idx) => {
  const [w1, w2, w3] = deterministicDistractors(ATLAS_ENTRIES, idx, 'name');
  return [`علم أي دولة أو جزيرة هذا؟ ${entry.flag}`, entry.name, w1, w2, w3];
});

/** 🏛️ ٢٣٠+ سؤال عاصمة تشمل عواصم الدول والجزر العالمية */
export const WORLD_CAPITALS_FULL: GQRow[] = ATLAS_ENTRIES.filter(e => e.capital && e.capital !== e.name).map((entry, idx, arr) => {
  const [w1, w2, w3] = deterministicDistractors(arr, idx, 'capital');
  return [`ما عاصمة ${entry.name} ${entry.flag}؟`, entry.capital!, w1, w2, w3];
});

