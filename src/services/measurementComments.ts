export function randomMeasurementComment(kind: MeasurementKind, value: number, random: () => number = Math.random): string {
  if (!Number.isInteger(value) || value < 0 || value > 100) throw new RangeError('Invalid measurement result');
  const band = Math.min(Math.floor(value / 20), 4);
  const choices = COMMENTS[kind][band];
  return choices[Math.floor(random() * choices.length)];
}
