import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { BookCatalog, memoryBookStorage } from '../src/services/bookCatalog';
import { TelegramBotManager } from '../server/telegramBot';

const bytes = Buffer.from('%PDF-1.4\nhello world\n%%EOF');
const hash = createHash('sha1').update(bytes).digest('hex');
let rights = 'Public Domain';
let sha = hash;
const catalogFetch = (async (input: any) => {
  const url = String(input);
  if (url.includes('/metadata/')) return new Response(JSON.stringify({ metadata: { rights }, files: [{ name: 'book.pdf', size: String(bytes.length), sha1: sha }] }));
  if (url.includes('/editions')) return new Response(JSON.stringify({ entries: [] }));
  return new Response('{}');
}) as typeof fetch;
const storage = memoryBookStorage();
await storage.put('books:chunk:0000', [{ id: 'OL1W', title: 'Book', author: 'Author', year: 1900, pages: 100, cover: null, lang: 'eng', subject: '', ia: 'testbook' }]);
const catalog = new BookCatalog(storage, catalogFetch);
const bot: any = new TelegramBotManager('test:token', '42', false, { bookStorage: storage });
bot.bookCatalog = catalog;
let docs: string[] = [];
let messages: string[] = [];
let rejectChannel = false;
bot.sendMessage = async (_: string, text: string) => { messages.push(text); return { ok: true }; };
bot.answerCallbackQuery = async () => ({ ok: true });
bot.sendPdfDocument = async (_: string, document: string) => { docs.push(document); return { ok: !(rejectChannel && document === 'file-id') }; };
let fileCalls = 0;
globalThis.fetch = (async (input: any) => {
  const url = String(input);
  if (url.endsWith('/getFile') || url.includes('/file/bot')) fileCalls++;
  if (url.endsWith('/getFile')) return new Response(JSON.stringify({ ok: true, result: { file_path: 'documents/file.pdf' } }));
  if (url.includes('/file/bot')) return new Response(bytes, { headers: { 'content-length': String(bytes.length) } });
  return new Response(JSON.stringify({ ok: true, result: { status: 'member' } }));
}) as typeof fetch;
const original: any = { message_id: 1, from: { id: 42, first_name: 'Owner' }, chat: { id: 42, type: 'private' }, date: 1, forward_origin: { type: 'channel', chat: { id: -1001, type: 'channel', username: 'lovekotob' } }, document: { file_id: 'file-id', file_size: bytes.length, mime_type: 'application/pdf' } };
await bot.handleMessage(original);
assert.equal(fileCalls, 2);
assert.match(messages[0], /انحفظ الملف/);
assert.equal(await catalog.channelPdf(hash, bytes.length), 'file-id');
assert.equal(await new BookCatalog(storage, catalogFetch).channelPdf(hash, bytes.length), 'file-id');
assert.equal(await catalog.channelPdf(hash, bytes.length + 1), null);
const cb: any = { id: 'cb', from: { id: 42, first_name: 'Owner' }, message: { message_id: 2, chat: { id: 42, type: 'private' } } };
await bot.handleExtraServicesCb(cb, 'svc:books:pdf:OL1W');
assert.deepEqual(docs, ['file-id']);
assert.equal(messages.length, 1);
rejectChannel = true; docs = [];
await bot.handleExtraServicesCb(cb, 'svc:books:pdf:OL1W');
assert.deepEqual(docs, ['file-id', 'https://archive.org/download/testbook/book.pdf']);
rejectChannel = false;
const protectedCatalog = new BookCatalog(storage, catalogFetch);
rights = 'Copyright'; bot.bookCatalog = protectedCatalog; docs = []; messages = [];
await bot.handleExtraServicesCb(cb, 'svc:books:pdf:OL1W');
assert.deepEqual(docs, []);
assert.ok(messages.some(m => m.includes('الملكية العامة')));
rights = 'Public Domain'; sha = 'a'.repeat(40); bot.bookCatalog = new BookCatalog(storage, catalogFetch); docs = [];
await bot.handleExtraServicesCb(cb, 'svc:books:pdf:OL1W');
assert.deepEqual(docs, ['https://archive.org/download/testbook/book.pdf']);
assert.equal(await bot.indexForwardedBookPdf({ ...original.document, file_size: 20 * 1024 * 1024 + 1 }), false);
assert.equal(await bot.indexForwardedBookPdf({ ...original.document, mime_type: 'text/plain' }), false);
assert.equal(await bot.indexForwardedBookPdf({ ...original.document, file_size: bytes.length + 1 }), false);
const callsBefore = fileCalls;
// Forwarded messages from other channels and non-owners cannot enter the index.
bot.indexForwardedBookPdf = async () => { throw new Error('must not index'); };
await bot.handleMessage({ ...original, from: { id: 43, first_name: 'Other' } });
await bot.handleMessage({ ...original, forward_origin: { type: 'channel', chat: { type: 'channel', username: 'anotherchannel' } } });
assert.equal(fileCalls, callsBefore);
console.log('Channel PDF checks passed.');
