import assert from 'node:assert/strict';
import { AmongUsRooms, memoryRoomStorage, type AuRoomState } from '../src/services/amongUsRooms';
const storage=memoryRoomStorage(), engine=new AmongUsRooms(storage);
const post=async(body:any)=>(await engine.handle(new Request('https://game.test/api/amongus/rooms',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(body)}))).json() as any;
const get=async(code:string,token:string)=>(await engine.handle(new Request(`https://game.test/api/amongus/rooms/${code}?token=${token}`))).json() as any;
const first=await post({action:'create',name:'الأول'});const code=first.code, tokens=[first.token];
for(let i=0;i<5;i++) tokens.push((await post({action:'join',code,name:`لاعب ${i}`})).token);
await post({action:'start',code,token:tokens[0]});
const key=`amongus-room:${code}`, state=(await storage.get<AuRoomState>(key))!;
state.players.forEach((p,i)=>{p.role=i===5?'impostor':'crew';p.alive=true;p.x=19;p.y=18});
const [viewer,hidden,near,corpse,med,imp]=state.players;
viewer.x=61;viewer.y=22; hidden.x=70;hidden.y=22; near.x=59;near.y=22;
corpse.alive=false;corpse.x=77;corpse.y=39;
state.bodies=[{playerId:corpse.token,name:corpse.name,color:corpse.color,x:77,y:39,room:'corridor',at:Date.now()}];
state.log.push({at:Date.now(),text:'صار قتل بالسفينة'});
await storage.put(key,state);
const r=await get(code,tokens[0]); const p=(name:string)=>r.room.players.find((p:any)=>p.name===name);
assert.equal(p(near.name).x,59,'near unobstructed player is visible');
assert.equal(p(hidden.name).x,null,'wall blocks sight even at close distance');
assert.equal(p(corpse.name).alive,true,'unreported death is hidden');
assert.equal(r.room.bodies.length,0,'distant corpse is not transmitted');
assert.equal(JSON.stringify(r.room).includes(corpse.token),false,'body and roster never leak another token');
assert.equal(JSON.stringify(r.room).includes(hidden.token),false,'player credentials never enter the room view');
assert.equal(r.room.log.some((v:any)=>v.text.includes('قتل')),false,'death is not leaked through logs');
const stolen=await post({action:'move',code,token:p(hidden.name).token,x:71,y:20});assert.equal(stolen.ok,false,'a public player id is not a credential');
const unauth=await get(code,'not-a-token');assert.equal(unauth.ok,false);
const viewBefore=await post({action:'cameras',code,token:viewer.token,enabled:true});assert.equal(viewBefore.ok,false,'must be near console');
viewer.x=24;viewer.y=49;med.x=32;med.y=20;imp.x=51;imp.y=49;
await storage.put(key,state);
const cameras=await post({action:'cameras',code,token:viewer.token,enabled:true});
assert.equal(cameras.ok,true);assert.equal(cameras.room.cameraFeeds.length,4);
assert.ok(cameras.room.cameraFeeds.some((f:any)=>f.players.some((q:any)=>q.name===med.name)),'hallway player visible on camera');
assert.ok(cameras.room.cameraFeeds.some((f:any)=>f.players.some((q:any)=>q.name===imp.name)),'other camera works');
assert.ok(cameras.room.cameraFeeds.every((f:any)=>f.players.every((q:any)=>q.name!==near.name)),'outside camera coverage stays private');
const other=await get(code,near.token);assert.equal(other.room.cameraFeeds,null,'no camera data for non-operators');
assert.equal(JSON.stringify(cameras.room).includes(imp.token),false,'camera feed does not leak credentials');
state.sabotage={kind:'comms',endsAt:0};await storage.put(key,state);
const disabled=await get(code,viewer.token);assert.equal(disabled.room.cameraFeeds,null,'comms disables cameras');
const closed=await post({action:'cameras',code,token:viewer.token,enabled:false});assert.equal(closed.ok,true);
state.sabotage=null;state.players.forEach(p=>{p.alive=true;p.x=50;p.y=12});
imp.x=60;imp.y=22;viewer.x=60;viewer.y=22;state.bodies=[];await storage.put(key,state);
const entered=await post({action:'vent',code,token:imp.token});assert.equal(entered.room.inVent,true);
assert.ok(entered.room.ventOptions.some((v:any)=>v.id==='admin'));
assert.ok(entered.room.ventOptions.some((v:any)=>v.id==='hall'));
assert.equal((await get(code,viewer.token)).room.players.find((p:any)=>p.name===imp.name).x,null,'vented player is hidden');
assert.equal((await post({action:'ventTravel',code,token:imp.token,target:'elec'})).ok,false,'unlinked vents cannot be used');
const through=await post({action:'ventTravel',code,token:imp.token,target:'admin'});assert.equal(through.room.players.find((p:any)=>p.you).x,64);
const emerged=await post({action:'ventExit',code,token:imp.token});assert.equal(emerged.room.inVent,false);
state.players.forEach(p=>{p.alive=true;p.x=50;p.y=12;p.ventId=null});state.phase='meeting';state.meeting={reason:'emergency',calledBy:viewer.token,startedAt:Date.now(),endsAt:Date.now()+40000,votes:{},chat:[]};await storage.put(key,state);
const vote=await post({action:'vote',code,token:viewer.token,target:hidden.publicId});assert.equal(vote.ok,true);
assert.equal(JSON.stringify(vote.room).includes(hidden.token),false,'own vote never leaks target credential');
console.log('Vision: distance, walls, unreported deaths, identity secrecy, authenticated four-camera views, sabotage and voting passed.');
