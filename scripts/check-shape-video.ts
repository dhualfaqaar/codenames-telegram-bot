import assert from 'node:assert/strict';
import { TelegramBotManager } from '../server/telegramBot';
const {default: worker, BotState} = await (new Function('url', 'return import(url)'))(new URL('../worker/index.ts', import.meta.url).href);

const json = (obj: unknown) => new Response(JSON.stringify(obj), {headers:{'content-type':'application/json'}});
let calls: Array<{method:string, init:any}> = [];
let rejectTelegramSend = false;
const originalFetch = globalThis.fetch;
globalThis.fetch = (async (input: any, init: any = {}) => {
  const url = String(input), method = url.split('/').pop()!;
  calls.push({method,init});
  if (url.includes('/file/bot')) return new Response(new Uint8Array([0,0,0,16,102,116,121,112,1,2,3,4,5,6,7,8]));
  if (method === 'getFile') return json({ok:true,result:{file_path:'videos/test.mp4',file_size:16}});
  if (rejectTelegramSend && ['sendVideoNote','sendVideo'].includes(method)) return json({ok:false,description:'rejected'});
  return json({ok:true,result:{message_id:12}});
}) as typeof fetch;
try {
  const bot = new TelegramBotManager('TEST:TOKEN') as any;
  const cb = {id:'cb', from:{id:12345, first_name:'User'}, message:{chat:{id:12345,type:'private'},message_id:7}};
  await bot.handleExtraServicesCb(cb,'svc:shapevideo');
  assert.equal(bot.shapeVideos.get('12345').fileId,'');
  await bot.handleShapeVideoInput('12345', {video:{file_id:'original',file_size:16,duration:1}});
  const draft = bot.shapeVideos.get('12345');
  assert.match(draft.session,/^[a-f0-9]{32}$/);
  const msg = calls.filter(c=>c.method==='sendMessage').at(-1)!;
  const keyboard = JSON.parse(msg.init.body).reply_markup.inline_keyboard;
  const links = keyboard.flat().filter((button:any)=>button.web_app).map((button:any)=>new URL(button.web_app.url));
  assert.deepEqual(links.map((u:URL)=>u.searchParams.get('shape')),['circle','star','hexagon','pentagon','triangle']);
  assert.ok(links.every((u:URL)=>u.pathname==='/shape-video/' && u.searchParams.get('session')===draft.session));
  assert.equal(bot.shapeVideoAllowed('12345',draft.session),true);
  assert.equal(bot.shapeVideoAllowed('12346',draft.session),false);
  assert.equal(bot.shapeVideoAllowed('12345','bad'),false);
  const copy = new TelegramBotManager('TEST:TOKEN') as any; copy.importState(bot.exportState());
  assert.equal(copy.shapeVideoAllowed('12345',draft.session),true, 'session survives state restore');
  let source = await bot.shapeVideoSource('12345',draft.session);
  assert.equal(source.status,200); assert.equal((await source.arrayBuffer()).byteLength,16);
  assert.equal((await bot.shapeVideoSource('12346',draft.session)).status,403);
  const output = new Uint8Array([0,0,0,16,102,116,121,112,1,2,3,4,5,6,7,8]);
  calls=[];
  assert.equal(await bot.sendShapeVideo('12345',draft.session,'circle',output),true);
  let call = calls.find(c=>c.method==='sendVideoNote')!;
  assert.ok(call); assert.equal(call.init.body.get('chat_id'),'12345'); assert.ok(call.init.body.get('video_note') instanceof Blob);
  assert.equal(await bot.sendShapeVideo('12345',draft.session,'star',output),true);
  call = calls.find(c=>c.method==='sendVideo')!;
  assert.ok(call.init.body.get('video') instanceof Blob);
  assert.equal(await bot.sendShapeVideo('12345',draft.session,'star',new Uint8Array(16)),false);
  assert.equal(await bot.sendShapeVideo('12346',draft.session,'circle',output),false);
  const old = draft.session;
  await bot.handleShapeVideoInput('12345',{video:{file_id:'new',file_size:16,duration:1}});
  assert.equal(bot.shapeVideoAllowed('12345',old),false, 'old links expire when a new video is sent');
  const current = bot.shapeVideos.get('12345'); current.at -= 3600_001;
  assert.equal(bot.shapeVideoAllowed('12345',current.session),false);
  await bot.handleShapeVideoInput('12345',{video:{file_id:'large',file_size:21*1024*1024,duration:1}});
  assert.notEqual(bot.shapeVideos.get('12345').fileId,'large');
  await bot.handleShapeVideoInput('12345',{video:{file_id:'long',file_size:16,duration:61}});
  assert.notEqual(bot.shapeVideos.get('12345').fileId,'long');

  // Sign real initData and exercise the public Worker authentication boundary.
  const token = '123456:TEST', fields = new URLSearchParams({auth_date:String(Math.floor(Date.now()/1000)),user:JSON.stringify({id:12345,first_name:'Test'})});
  const check = Array.from(fields.entries()).sort(([a],[b])=>a<b?-1:a>b?1:0).map(([k,v])=>`${k}=${v}`).join('\n');
  const encoder = new TextEncoder(), algorithm = {name:'HMAC',hash:'SHA-256'};
  const key = await crypto.subtle.importKey('raw',encoder.encode('WebAppData'),algorithm,false,['sign']);
  const secret = await crypto.subtle.sign('HMAC',key,encoder.encode(token));
  const hmac = await crypto.subtle.importKey('raw',secret,algorithm,false,['sign']);
  const hash = new Uint8Array(await crypto.subtle.sign('HMAC',hmac,encoder.encode(check)));
  fields.set('hash',Array.from(hash,b=>b.toString(16).padStart(2,'0')).join(''));
  const seen: Array<{url:string,init:any}> = [];
  const env = {TELEGRAM_BOT_TOKEN:token,BOT_STATE:{idFromName:()=>1,get:()=>({fetch:async (url:string,init:any)=>{seen.push({url,init}); return new Response('ok');}})}};
  const context = {} as any;
  const headers = {'authorization':`tma ${fields}`,'x-shape-session':'a'.repeat(32),'x-shape-kind':'circle','x-shape-user':'99999'};
  const request = (headers:Record<string,string>, body?:BodyInit) => new Request('https://game.test/api/shape-video/source',{method:'POST',headers,body});
  assert.equal((await worker.fetch(request(headers),env,context)).status,200);
  assert.equal(seen.at(-1)!.init.headers.get('x-shape-user'),'12345', 'client cannot choose recipient');
  assert.equal(seen.at(-1)!.init.headers.get('authorization'),null, 'signed payload not passed unnecessarily');
  const n = seen.length;
  assert.equal((await worker.fetch(request({...headers,authorization:'tma invalid'}),env,context)).status,401);
  assert.equal((await worker.fetch(request({...headers,'x-shape-session':'bad'}),env,context)).status,401);
  assert.equal((await worker.fetch(request({...headers,'x-shape-kind':'other'}),env,context)).status,401);
  assert.equal(seen.length,n);
  const large = new Request('https://game.test/api/shape-video/send',{method:'POST',headers,body:new Uint8Array(15*1024*1024+1)});
  assert.equal((await worker.fetch(large,env,context)).status,413);
  assert.equal(seen.length,n);
  // Run the authenticated outer Worker through the actual DO routing and bot methods.
  await bot.handleShapeVideoInput('12345',{video:{file_id:'source',file_size:16,duration:1}});
  const liveSession = bot.shapeVideos.get('12345').session;
  const realHeaders = {...headers,'x-shape-session':liveSession};
  const instance = Object.create(BotState.prototype);
  instance.getBot = async () => bot;
  const integratedEnv = {...env,BOT_STATE:{idFromName:()=>1,get:()=>({fetch:(url:string,init:any)=>instance.fetch(new Request(url,init))})}};
  const getSource = await worker.fetch(request(realHeaders),integratedEnv,context);
  assert.equal(getSource.status,200);
  assert.equal((await getSource.arrayBuffer()).byteLength,16);
  const upload = () => new Request('https://game.test/api/shape-video/send',{method:'POST',headers:realHeaders,body:output});
  assert.equal((await worker.fetch(upload(),integratedEnv,context)).status,200);
  rejectTelegramSend = true;
  assert.equal((await worker.fetch(upload(),integratedEnv,context)).status,502, 'Telegram rejection is reported, not success');
  rejectTelegramSend = false;
  assert.equal((await worker.fetch(request({...realHeaders,'x-shape-session':'b'.repeat(32)}),integratedEnv,context)).status,403);
  console.log('Video shape bot flow and signed Worker security checks passed.');
} finally { globalThis.fetch = originalFetch; }
